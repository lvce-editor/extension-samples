import { expect, test, type Locator, type Page } from '@playwright/test'

const sizeSymbol = /^size$/

const formatDocument = async (page: Page, editor: Locator): Promise<void> => {
  await editor.locator('.EditorRow').first().click({ button: 'right' })
  await page.getByRole('menuitem', { exact: true, name: 'Format Document' }).click()
  await expect(page.getByRole('menuitem', { exact: true, name: 'Format Document' })).toBeHidden()
}

test('diagnostics track TODO markers as the preview document changes', async ({ page }) => {
  await page.goto('/extension-samples/diagnostic-provider/')
  const editor = page.locator('#preview-ide .Editor')
  await expect(editor.locator('.DiagnosticError')).toHaveCount(2, { timeout: 30_000 })
  const problems = page.locator('#preview-ide .Problems')
  await expect(problems).toBeVisible()
  await expect(problems.getByText('Replace TODO with a setting value.', { exact: true })).toHaveCount(2)
  await expect(page.locator('#source-ide .Problems')).toBeHidden()
  await editor.locator('textarea').focus()
  await page.keyboard.press('Control+a')
  await page.keyboard.insertText('color=blue\nsize=large\n')
  await expect(editor.locator('.DiagnosticError')).toHaveCount(0)
  await page.keyboard.press('Control+a')
  await page.keyboard.insertText('color=TODO TODO\n')
  await expect(editor.locator('.DiagnosticError')).toHaveCount(2)
  await expect(page.locator('#source-ide .DiagnosticError')).toHaveCount(0)
})

test('completion filters a typed prefix and inserts the selected color', async ({ page }) => {
  await page.goto('/extension-samples/completion-provider/')
  const editor = page.locator('#preview-ide .Editor')
  await expect(editor).toContainText('color=', { timeout: 30_000 })
  const items = page.locator('.EditorCompletionItem')
  await expect(items).toHaveText(['blue', 'green', 'red'])
  await expect(page.locator('#preview-status')).toHaveText('Preview ready')
  await expect(page.locator('#source-ide .Editor')).toContainText('registerCompletionProvider')
  await page.keyboard.press('Escape')
  await page.keyboard.insertText('gr')
  await page.keyboard.press('Control+Space')
  await expect(items).toHaveText(['green'])
  await page.keyboard.press('Enter')
  await expect(editor.locator('.EditorRow').first()).toHaveText('color=green')
  await expect(page.locator('.EditorCompletion')).toBeHidden()
})

test('source editor provides TypeScript completions for the sample files', async ({ page }) => {
  await page.goto('/extension-samples/file-system-provider/')
  await expect(page.locator('body')).toHaveAttribute('data-playground-ready', 'true', { timeout: 30_000 })
  const editor = page.locator('#source-ide .Editor')
  const textarea = editor.locator('textarea')
  await expect(editor).toContainText('const fileStore', { timeout: 30_000 })
  await textarea.focus()
  await page.keyboard.press('Control+a')
  await page.keyboard.insertText('const fileStore = {}\nfileSto')
  await expect(editor.locator('.EditorRow').last()).toHaveText('fileSto')
  await page.keyboard.press('Control+Space')
  const completion = page.getByRole('option', { exact: true, name: 'fileStore' })
  await expect(completion).toBeVisible({ timeout: 30_000 })
  await page.keyboard.press('Enter')
  await expect(editor.locator('.EditorRow').last()).toHaveText('fileStore')
})

test('hover shows documentation only for a recognized word', async ({ page }) => {
  await page.goto('/extension-samples/hover-provider/')
  const editor = page.locator('#preview-ide .Editor')
  await expect(editor).toContainText('blue green red unknown', { timeout: 30_000 })
  await expect(page.locator('.EditorHover')).toContainText('Blue: the color of a clear sky.')
  await expect(page.locator('#preview-status')).toHaveText('Preview ready')
  await page.keyboard.press('Escape')
  await page.keyboard.press('End')
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('Control+h')
  await expect(page.locator('.EditorHover')).toBeHidden()
})

test('formatting normalizes settings and can be undone', async ({ page }) => {
  await page.goto('/extension-samples/formatting-provider/')
  const editor = page.locator('#preview-ide .Editor')
  await expect(editor).toContainText('color=blue', { timeout: 30_000 })
  await editor.locator('textarea').focus()
  await formatDocument(page, editor)
  await expect(editor.locator('.EditorRow')).toHaveText(['color = blue', 'size = large', ''])
  await formatDocument(page, editor)
  await expect(editor.locator('.EditorRow')).toHaveText(['color = blue', 'size = large', ''])
  await editor.locator('textarea').focus()
  await page.keyboard.press('Control+z')
  await expect(editor.locator('.EditorRow')).toHaveText(['  color=blue  ', 'size =large', ''])
})

test('document symbols follow the preview cursor and unsaved declarations', async ({ page }) => {
  await page.goto('/extension-samples/document-symbol-provider/')
  const editor = page.locator('#preview-ide .Editor')
  const breadcrumb = page.locator('#preview-ide .EditorBreadcrumbSymbol')
  await expect(page.locator('#preview-status')).toHaveText('Preview ready', { timeout: 30_000 })
  await editor.locator('.EditorRow').first().click()
  await editor.locator('textarea').focus()
  await page.keyboard.press('Control+Home')
  await page.keyboard.press('ArrowRight')
  await expect(breadcrumb).toHaveText('color')
  await page.keyboard.press('Home')
  await page.keyboard.insertText('new_')
  await expect(breadcrumb).toHaveText('new_color')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Home')
  await page.keyboard.press('ArrowRight')
  await expect(breadcrumb).toHaveText('size')
  await page.keyboard.press('End')
  await expect(breadcrumb).toHaveCount(0)
  await expect(page.locator('#source-ide .EditorBreadcrumbSymbol').filter({ hasText: sizeSymbol })).toHaveCount(0)
})
