test('sample tokenizer highlights Sprout files and survives preview edits and reset', async ({ page }) => {
  await page.goto('/extension-samples/syntax-highlighting/')
  const editor = page.locator('#preview-ide .Editor')
  await expect(page.locator('#preview-status')).toHaveText('Preview ready', { timeout: 30_000 })
  await expect(editor.locator('.Token.Keyword').first()).toHaveText('let')
  await expect(editor.locator('.Token.String').first()).toContainText('Hello, Sprout!')
  await expect(editor.locator('.Token.Numeric').first()).toHaveText('3')
  await expect(editor.locator('.Token.Comment')).toContainText('A tiny Sprout program')

  const textarea = editor.locator('textarea')
  await textarea.focus()
  await page.keyboard.press('ControlOrMeta+a')
  await page.keyboard.insertText('let greeting = "Updated"\nprint(42)\n')
  await expect(editor.locator('.Token.String')).toContainText('Updated')
  await expect(editor.locator('.Token.Numeric')).toContainText('42')

  const source = page.locator('#source-ide .Editor')
  await source.locator('textarea').focus()
  await page.keyboard.press('ControlOrMeta+End')
  await page.keyboard.insertText('\n// Saved syntax highlighting sample\n')
  await page.keyboard.press('ControlOrMeta+s')
  await expect(page.locator('body')).toHaveAttribute('data-preview-revision', '2')
  await expect(editor.locator('.Token.String')).toContainText('Hello, Sprout!')
  await expect(editor.locator('.Token.Numeric')).toHaveText('3')

  const filesResponse = await page.request.get('/extension-samples/samples/syntax-highlighting/files.json')
  const files = await filesResponse.json()
  await page.locator('#source-ide').getByRole('treeitem', { exact: true, name: 'src' }).click()
  await page.locator('#source-ide').getByRole('treeitem', { exact: true, name: 'tokenizeSprout.js' }).click()
  await expect(source).toContainText('TokenMap')
  await source.locator('textarea').focus()
  await page.keyboard.press('ControlOrMeta+a')
  await page.keyboard.insertText(files['/src/tokenizeSprout.js'].replace("'Keyword'", "'String'"))
  await page.keyboard.press('ControlOrMeta+s')
  await expect(page.locator('body')).toHaveAttribute('data-preview-revision', '3')
  await expect(editor.locator('.Token.Keyword')).toHaveCount(0)
  await expect(editor.locator('.Token.String').first()).toHaveText('let')

  await page.getByRole('button', { name: 'Reset sample' }).click()
  await expect(page.locator('body')).toHaveAttribute('data-preview-revision', '1')
  await expect(editor.locator('.Token.String').first()).toContainText('Hello, Sprout!')
})

