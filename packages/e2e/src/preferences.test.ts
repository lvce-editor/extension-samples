import { expect, test } from '@playwright/test'
import { captureInputDiagnostics } from './CaptureInputDiagnostics.ts'
import { runCommand } from './RunCommand.ts'

test.beforeEach(async ({ page }) => {
  await captureInputDiagnostics(page)
})

test('preference sample reads, updates, cancels, and restores an editor setting', async ({ page }) => {
  await page.goto('/extension-samples/preferences/')
  await expect(page.locator('#preview-status')).toHaveText('Preview ready', { timeout: 30_000 })
  const editor = page.locator('#preview-ide .Editor')
  const editorRow = editor.locator('.EditorRow').first()
  const sourceRow = page.locator('#source-ide .EditorRow').first()
  const sourceFontSize = await sourceRow.evaluate((element) => getComputedStyle(element).fontSize)
  const sourceRowHeight = await sourceRow.evaluate((element) => getComputedStyle(element).height)
  const originalRowHeight = await editorRow.evaluate((element) => getComputedStyle(element).height)
  const minimumRowHeight = Number(originalRowHeight.replace('px', ''))
  const originalFontSize = await editorRow.evaluate((element) => getComputedStyle(element).fontSize)
  await runCommand(page, 'Sample: Inspect Configuration')
  await expect(page.locator('#preview-ide .OutputContent')).toContainText('Sample font size definition:')
  await expect(page.locator('#preview-ide .OutputContent')).toContainText('"default":18')
  await expect(page.locator('#preview-ide .OutputContent')).toContainText('Color themes:')
  await runCommand(page, 'Sample: Set Font Size')
  await expect(page.locator('#preview-ide .QuickPick')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('#preview-ide .QuickPick')).toBeHidden()
  await expect(editorRow).toHaveCSS('font-size', originalFontSize)
  await runCommand(page, 'Sample: Set Font Size')
  await page.locator('#preview-ide .QuickPick').getByRole('option').filter({ hasText: '18' }).click()
  const output = page.locator('#preview-ide .OutputContent')
  await expect(output).toContainText('Updated editor.fontSize: 18')
  await expect(editorRow).toHaveCSS('font-size', '18px')
  await expect(editorRow).toHaveCSS('height', `${Math.max(minimumRowHeight, 18)}px`)
  await expect(sourceRow).toHaveCSS('font-size', sourceFontSize)
  await runCommand(page, 'Sample: Set Font Size')
  await page.locator('#preview-ide .QuickPick').getByRole('option').filter({ hasText: '24' }).click()
  await expect(editorRow).toHaveCSS('font-size', '24px')
  await expect(editorRow).toHaveCSS('height', `${Math.max(minimumRowHeight, 24)}px`)
  await expect(sourceRow).toHaveCSS('font-size', sourceFontSize)
  await expect(sourceRow).toHaveCSS('height', sourceRowHeight)
  await runCommand(page, 'Sample: Reset Font Size')
  await expect(output).toContainText(`Restored editor.fontSize: ${Number(originalFontSize.replace('px', ''))}`)
  await expect(editorRow).toHaveCSS('font-size', originalFontSize)
  await expect(editorRow).toHaveCSS('height', originalRowHeight)
})
