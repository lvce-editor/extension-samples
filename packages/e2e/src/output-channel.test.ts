import { expect, test } from '@playwright/test'
import { runCommand } from './RunCommand.ts'

test('output channel appends successive builds and clears only preview output', async ({ page }) => {
  await page.goto('/extension-samples/')
  await page.getByRole('combobox', { name: 'Extension sample' }).selectOption({ label: 'Output Channel' })
  await expect(page.locator('body')).toHaveAttribute('data-playground-ready', 'true', { timeout: 30_000 })
  const output = page.locator('#preview-ide .OutputContent')
  await expect(output).toContainText('Ready.')
  await runCommand(page, 'Sample: Run Build')
  await expect(output).toContainText('Build 1: starting')
  await expect(output).toContainText('Compiling example.sample... done')
  await expect(output).toContainText('Build succeeded.')
  await runCommand(page, 'Sample: Run Build')
  await expect(output).toContainText('Build 1: starting')
  await expect(output).toContainText('Build 2: starting')
  await runCommand(page, 'Sample: Clear Build Output')
  await expect(output).toHaveText('')
  await expect(page.locator('#source-ide .OutputContent')).toHaveCount(0)
  await page.reload()
  await expect(page.locator('body')).toHaveAttribute('data-playground-ready', 'true', { timeout: 30_000 })
  await expect(output).toContainText('Ready.')
  await runCommand(page, 'Sample: Run Build')
  await expect(output).toContainText('Build 1: starting')
  await expect(output).toContainText('Build succeeded.')
  await expect(page.locator('#source-ide .OutputContent')).toHaveCount(0)
})

test('output channel reloads edited source and reset restores the original build message', async ({ page }) => {
  await page.goto('/extension-samples/output-channel/')
  await expect(page.locator('body')).toHaveAttribute('data-playground-ready', 'true', { timeout: 30_000 })
  const response = await page.request.get('/extension-samples/samples/output-channel/files.json')
  const files = await response.json()
  await page.locator('#source-ide .Editor textarea').focus()
  await page.keyboard.press('Control+a')
  await page.keyboard.insertText(files['/src/main.ts'].replace('Build succeeded.', 'Edited build succeeded.'))
  await page.keyboard.press('Control+s')
  await expect(page.locator('body')).toHaveAttribute('data-preview-revision', '2')
  await runCommand(page, 'Sample: Run Build')
  await expect(page.locator('#preview-ide .OutputContent')).toContainText('Edited build succeeded.')
  await expect(page.locator('#preview-ide .OutputContent')).toContainText('Build 1: starting')
  await page.getByRole('button', { name: 'Reset sample' }).click()
  await expect(page.locator('body')).toHaveAttribute('data-playground-ready', 'true', { timeout: 30_000 })
  await expect(page.locator('body')).toHaveAttribute('data-preview-revision', '1')
  await runCommand(page, 'Sample: Run Build')
  const output = page.locator('#preview-ide .OutputContent')
  await expect(output).toContainText('Build succeeded.')
  await expect(output).not.toContainText('Edited build succeeded.')
})
